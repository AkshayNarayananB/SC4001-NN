"""Selective answering: does a method know when it doesn't know? (risk-coverage on POPE TEST images)

    python -m scripts.analyze_selective

Each method answers Yes iff score > its threshold (DEV-tuned for * rows). Confidence = |score - threshold|.
The model may abstain on its least-confident questions; at coverage c it answers the most confident c share
of each TEST cell. Reported: accuracy at coverage 100/90/80/70/50%, and AURC (area under the risk-coverage
curve, mean error over all coverages; lower is better). Means over the 27 condition x split cells, plus the
two hardest conditions. Reads results/layers_scores.npz (written by scripts.analyze_layers).
Writes results/selective_table.{csv,md}.
"""
import numpy as np
import pandas as pd

from src.paths import REPO_ROOT

COVERAGES = (1.0, 0.9, 0.8, 0.7, 0.5)
METHODS = None  # all * rows plus baseline threshold 0


def risk_coverage(score, thr, gold):
    conf = np.abs(score - thr)
    order = np.argsort(-conf, kind="stable")
    correct = ((score > thr) == gold)[order]
    cum_acc = np.cumsum(correct) / np.arange(1, len(correct) + 1)
    acc_at = {c: cum_acc[max(int(round(c * len(correct))) - 1, 0)] for c in COVERAGES}
    return acc_at, float(np.mean(1 - cum_acc))


def main():
    z = np.load(REPO_ROOT / "results" / "layers_scores.npz")
    keys = list(z.keys())
    thr = {k.split("|", 1)[1]: float(z[k]) for k in keys if k.startswith("__thr|")}
    gold = {tuple(k.split("|")[1:]): z[k] for k in keys if k.startswith("__gold|")}
    methods = [m for m in thr if m.endswith("*") or m == "Baseline (threshold 0)"]
    methods = [m for m in methods if "Object prior" not in m and not m.startswith("Probe L8")]
    rows = []
    for m in methods:
        for cell, g in gold.items():
            acc, aurc = risk_coverage(z["|".join([m, *cell])], thr[m], g)
            rows.append(dict(method=m, kind=cell[0], level=int(cell[1]), split=cell[2], aurc=aurc,
                             **{f"acc@{int(c * 100)}": v for c, v in acc.items()}))
    df = pd.DataFrame(rows)
    cols = ["aurc"] + [f"acc@{int(c * 100)}" for c in COVERAGES]
    allc = df.groupby("method", sort=False)[cols].mean()
    hard = df[(df.level == 4)].groupby(["method", "kind"], sort=False)[cols].mean().unstack("kind")
    table = allc.join(hard[[("aurc", "blur"), ("aurc", "noise"), ("acc@80", "blur"), ("acc@80", "noise")]].set_axis(
        ["aurc blur s4", "aurc noise s4", "acc@80 blur s4", "acc@80 noise s4"], axis=1))
    table = table.sort_values("aurc")
    table.to_csv(REPO_ROOT / "results" / "selective_table.csv", float_format="%.4f")
    lines = ["| Method | AURC ↓ | Acc @100% | @90% | @80% | @70% | @50% | AURC blur s4 | AURC noise s4 | Acc@80% blur s4 | Acc@80% noise s4 |",
             "|---|" + "---|" * 10]
    for m, r in table.iterrows():
        lines.append(f"| {m} | {r['aurc']:.3f} | " + " | ".join(f"{100 * r[f'acc@{int(c * 100)}']:.1f}" for c in COVERAGES)
                     + f" | {r['aurc blur s4']:.3f} | {r['aurc noise s4']:.3f} | {100 * r['acc@80 blur s4']:.1f} | {100 * r['acc@80 noise s4']:.1f} |")
    md = "\n".join(["Selective answering on TEST images (27 cells): abstain on the least-confident questions. "
                    "AURC = mean error over all coverage levels (lower is better).", "", *lines, "",
                    "Generated by `python -m scripts.analyze_selective`."])
    (REPO_ROOT / "results" / "selective_table.md").write_text(md + "\n")
    print(md)


if __name__ == "__main__":
    main()
